// prism-css-extras узнаёт цвет только в устаревшем синтаксисе с запятыми:
// hsl(0, 100%, 50%) / rgb(255, 0, 0) / rgba(255, 0, 0, .5).
// Современный синтаксис с пробелами и слэшем (rgb(255 0 0 / .5)), а также
// hwb(), lab(), lch(), oklab(), oklch(), color() и color-mix() он не понимает
// вовсе — превьюшка цвета рядом с кодом для них не появляется.
//
// Переопределяем правило 'color', чтобы ловить любой вызов
// перечисленных цветовых функций целиком, независимо от синтаксиса внутри.
// Правило только размечает границы токена — какой именно это цвет,
// определяет браузер через нативный CSS при отрисовке превьюшки
// (см. prismjs/plugins/inline-color).
module.exports = function (Prism) {
  var namedColors = Prism.languages.css.color[0]

  // Вставляем перед 'operator' — самым ранним из конкурирующих правил
  // css-extras. 'operator' режет одиночный слэш в rgb(... / ...) на свой
  // токен, а 'entity'/'unit'/'number' дробят числа — оба должны остаться
  // ПОСЛЕ 'color' в порядке правил, иначе строка разобьётся на куски
  // раньше, чем до неё дойдёт очередь у правила color, и оно не сможет
  // схватить вызов функции целиком.
  Prism.languages.insertBefore('css', 'operator', {
    color: [
      // Функциональный вызов — первым: relative color syntax может
      // ссылаться на именованный цвет внутри себя (rgb(from green r g b
      // / 0.5)). Если сначала забрать "green" как отдельный токен, вызов
      // целиком уже не собрать — строка окажется раздроблена.
      {
        // хотя бы один уровень вложенных скобок нужен для relative color
        // syntax (rgb(from hwb(...) r g b)) и calc() внутри каналов
        pattern: /\b(?:hsla?|rgba?|hwb|lab|lch|oklab|oklch|color-mix|color)\((?:[^()]|\([^()]*\))*\)/i,
        inside: {
          unit: /\b(?:deg|grad|rad|turn)\b|%/,
          number: /-?\b\d*\.?\d+\b/,
          function: /[\w-]+(?=\()/,
          punctuation: /[(),/]/,
        },
      },
      // Именованные цвета — вторым: только то, что не забрала функция.
      namedColors,
    ],
  })
}
