// Поэтому ни кеширование, ни офлайн-режим не действовали ни у кого, зато в
// консоли у каждого посетителя копились ошибки.
//
// Одной починки обработчика мало: под ним слой кеширования сломан не меньше.
// putResInCache вычитывает тело ответа и отдаёт браузеру тот же объект с уже
// прочитанным телом, а тип ресурса вычисляется по объекту запроса вместо пути,
// из-за чего любой файл кешируется как text/html. Включённый воркер в таком
// виде ломает загрузку стилей, скриптов и шрифтов, то есть хуже, чем никакого.
// Пока это не починено и не покрыто тестами, воркер выключен целиком.
//
// Файл остаётся на месте и по-прежнему отдаётся по адресу /sw.js — это важно.
// Браузеры уже установленных воркеров периодически перезапрашивают этот адрес,
// и, получив такой код, снимают регистрацию и чистят за собой кеши. Если файл
// удалить, старый сломанный воркер останется у посетителей навсегда.

// Префикс всех кешей, которые заводил прежний воркер. Чистим только их, чтобы
// не задеть чужие кеши на том же домене.
const CACHE_PREFIX = 'doka-'

self.addEventListener('install', () => {
  // Не ждём, пока закроются вкладки со старым воркером: чем раньше этот
  // возьмётся за дело, тем раньше снимет регистрацию.
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const cacheNames = await caches.keys()
      await Promise.all(cacheNames.filter((name) => name.startsWith(CACHE_PREFIX)).map((name) => caches.delete(name)))

      await self.registration.unregister()
    })(),
  )
})

